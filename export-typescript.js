/**
 * Infer component/module names from the file name.
 * Supports patterns like:
 *   "Master_Customer-EX5010.xlsx" → module: "MasterCustomer", exCode: "EX5010", component: "EX5010"
 *   "EX5010_Master.xlsx"         → module: "Master", exCode: "EX5010", component: "EX5010"
 *   "my-report.xlsx"             → module: "MyReportManagement", exCode: "MyReport", component: "MyReportComponent"
 */
function inferComponentNames(fileName) {
  if (!fileName) {
    return {
      moduleName: 'LECDReportManagement',
      exCode: 'EX0000',
      componentName: 'EX0000Component'
    };
  }

  let base = fileName.replace(/\.xlsx$/i, '').trim();

  // If file has underscore pattern, extract EX code and module name
  if (base.includes('_')) {
    // Extract EX code pattern (EX followed by digits) from the entire string
    const exMatch = base.match(/EX\d+/);
    const exCode = exMatch ? exMatch[0] : 'EX0000';

    // Remove the EX code to get the module name parts
    let modBase = base;
    if (exMatch) {
      modBase = modBase.replace(exMatch[0], '').trim();
    }

    // Clean up and build PascalCase module name
    const moduleName = modBase
      .replace(/[^a-zA-Z0-9]/g, ' ')
      .split(/\s+/)
      .filter(Boolean)
      .map(w => w.charAt(0).toUpperCase() + w.slice(1))
      .join('') || 'LECDReportManagement';

    return {
      moduleName: moduleName,
      exCode: exCode,
      componentName: exCode
    };
  }

  // Default: use file name as the component/EX code
  const cleanName = base
    .replace(/[^a-zA-Z0-9]/g, ' ')
    .split(/\s+/)
    .filter(Boolean)
    .map(w => w.charAt(0).toUpperCase() + w.slice(1))
    .join('');

  return {
    moduleName: cleanName + 'Management',
    exCode: cleanName,
    componentName: cleanName + 'Component'
  };
}

/**
 * Convert header text to camelCase TypeScript property name
 */
function toCamelCaseTs(str) {
  if (!str) return 'empty';
  return str
    .replace(/[^a-zA-Z0-9\u0E00-\u0E7F ]/g, ' ')
    .split(/\s+/)
    .filter(Boolean)
    .map((word, i) => {
      if (i === 0) return word.charAt(0).toLowerCase() + word.slice(1);
      return word.charAt(0).toUpperCase() + word.slice(1);
    })
    .join('')
    .replace(/^[0-9]/, m => '_' + m) || 'field';
}

/**
 * Infer TypeScript type from Excel cell
 */
function inferTsType(cell) {
  if (!cell) return 'string';

  const numFmt = (cell.numFmt || '').toLowerCase().trim();
  const isDateFormat = /(yy|yyyy|dd|mmm)/i.test(numFmt);
  const hasTime = /h/.test(numFmt) || /m.*s/.test(numFmt) || /s$/.test(numFmt);

  if (isDateFormat || hasTime) {
    return 'Date';
  }

  if (cell.value != null && typeof cell.value === 'number') {
    return 'number';
  }

  if (cell.value != null && typeof cell.value === 'boolean') {
    return 'boolean';
  }

  if (numFmt.includes('%') || numFmt.includes('0.00') || numFmt.includes('#,##0')) {
    return 'number';
  }

  return 'string';
}

/**
 * Infer TypeScript type from column header name (fallback)
 */
function inferTsTypeFromName(headerName) {
  if (!headerName) return 'string';
  const name = headerName.toLowerCase();

  if (name.includes('date') || name.includes('time') || name === 'created' || name === 'updated') {
    return 'Date';
  }

  if (name.includes('tax') || name.includes('total') || name.includes('amount') ||
      name.includes('sum') || name.includes('price') || name.includes('cost') ||
      name.includes('fee') || name.includes('rate') || name.includes('qty') ||
      name.includes('quantity') || name.includes('balance') || name.includes('net') ||
      name.includes('gross') || name.includes('discount') || name.includes('vat') ||
      name.includes('percent') || name.includes('count') || name.includes('number')) {
    return 'number';
  }

  if (name.startsWith('is') || name.startsWith('has') || name.startsWith('flag') ||
      name === 'active' || name.includes('enable') || name.includes('status')) {
    return 'boolean';
  }

  return 'string';
}

/**
 * Get default TypeScript value for a type
 */
function getDefaultTsValue(tsType) {
  switch (tsType) {
    case 'number': return '0';
    case 'boolean': return 'false';
    case 'Date': return 'null';
    default: return '""';
  }
}

/**
 * Escape HTML for use in template
 */
function escapeHtml(str) {
  if (!str) return '';
  const div = document.createElement('div');
  div.textContent = str;
  return div.innerHTML;
}
